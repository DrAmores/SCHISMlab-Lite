"""Informe automático de una simulación: un HTML autocontenido (figuras incrustadas) listo para entregar o imprimir en PDF.

Contenido: identificación del caso, configuración (YAML), malla (calidad y figura), forzamientos y contornos,
parámetros clave de param.nml, mapas de cada variable guardada al final de la simulación (y máximos),
series en las estaciones y, en 3D, una sección vertical.
"""
from __future__ import annotations
import base64
import html
import io
import json
import re
from pathlib import Path
import numpy as np
import yaml


def _png(fig) -> str:
    buf = io.BytesIO(); fig.savefig(buf, format="png", dpi=90, bbox_inches="tight"); import matplotlib.pyplot as plt; plt.close(fig)
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()


def _file_png(path: Path) -> str:
    return "data:image/png;base64," + base64.b64encode(path.read_bytes()).decode()


def _param_summary(param_file: Path) -> dict:
    txt = param_file.read_text(errors="ignore")
    keys = ["rnday", "dt", "ibc", "ibtp", "nws", "ihconsv", "isconsv", "nchi", "ihorcon", "hvis_coef0", "itur", "ncor", "ics", "if_source", "icou_elfe_wwm", "nspool", "ihfskip", "ihot", "inv_atm_bnd", "inu_uv"]
    out = {}
    for k in keys:
        m = re.search(rf"^\s*{k}\s*=\s*([^!\n]+)", txt, re.M)
        if m:
            out[k] = m.group(1).strip()
    return out


def build_report(case_path: str | Path, out: str | Path | None = None, lang: str = "es", author: str = "") -> Path:
    import matplotlib; matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from ..case import Case
    from .output import open_run, read_stations
    from .plots import plot_map, plot_section
    from ..io.namelist_catalog import DESC
    case = Case(case_path); wd = case.workdir; cfg = case.cfg
    out = Path(out or wd / f"informe_{case.cfg.get('name', wd.name)}.html")
    es = lang == "es"
    L = (lambda a, b: a if es else b)
    parts = [f"<h1>{html.escape(str(cfg.get('name', wd.name)))}</h1>"]
    parts.append(f"<p class='meta'>{L('Informe generado por SCHISMlab', 'Report generated by SCHISMlab')} · {np.datetime_as_string(np.datetime64('now'), 'm')}"
                 + (f" · {html.escape(author)}" if author else "") + "</p>")
    # configuracion
    parts.append(f"<h2>{L('Configuración del caso', 'Case configuration')}</h2><pre>{html.escape(yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True))}</pre>")
    # malla
    q = json.loads((wd / "mesh_quality.json").read_text()) if (wd / "mesh_quality.json").exists() else {}
    if q:
        rows = "".join(f"<tr><td>{html.escape(str(k))}</td><td>{v:.4g}</td></tr>" if isinstance(v, (int, float)) else f"<tr><td>{html.escape(str(k))}</td><td>{html.escape(str(v))}</td></tr>" for k, v in q.items())
        parts.append(f"<h2>{L('Malla', 'Mesh')}</h2><table>{rows}</table>")
    if (wd / "mesh.png").exists():
        parts.append(f"<img src='{_file_png(wd / 'mesh.png')}' style='max-width:900px'>")
    # parametros
    if (wd / "param.nml").exists():
        ps = _param_summary(wd / "param.nml")
        rows = "".join(f"<tr><td><code>{k}</code></td><td>{html.escape(v)}</td><td class='help'>{html.escape((DESC.get(k) or ('', ''))[0 if es else 1])}</td></tr>" for k, v in ps.items())
        parts.append(f"<h2>{L('Parámetros clave (param.nml)', 'Key parameters (param.nml)')}</h2><table>{rows}</table>")
    for name in ("wwminput.nml", "sediment.nml", "ice.nml", "source_sink.in", "bctides.in"):
        if (wd / name).exists():
            txt = (wd / name).read_text(errors="ignore")
            parts.append(f"<details><summary>{name}</summary><pre>{html.escape(txt[:20000])}</pre></details>")
    # resultados
    if (wd / "outputs").exists() and list((wd / "outputs").glob("out2d_*.nc")):
        ds = open_run(wd)
        parts.append(f"<h2>{L('Resultados', 'Results')}</h2><p>{L('Instantes guardados', 'Saved instants')}: {ds.time.size} · "
                     f"{np.datetime_as_string(ds.time.values[0], 'm')} → {np.datetime_as_string(ds.time.values[-1], 'm')}</p>")
        vars_ = sorted({v[:-1] if v.endswith(("X", "Y")) else v for v in ds.data_vars if "time" in ds[v].dims and not v.startswith("dryFlag")})
        for v in vars_:
            try:
                fig, ax = plt.subplots(1, 2, figsize=(14, 5))
                plot_map(ds, v, time=-1, ax=ax[0], vectors=(v + "X" in ds)); ax[0].set_title(f"{v} · {L('final', 'end')}")
                field = ds[v] if v in ds else np.hypot(ds[v + "X"], ds[v + "Y"])
                if "layer" in field.dims:
                    field = field.isel(layer=-1)
                mx = field.max(dim="time").values
                from .plots import _tri
                c = ax[1].tripcolor(*_tri(ds), np.nan_to_num(mx), shading="gouraud"); plt.colorbar(c, ax=ax[1]); ax[1].set_title(f"{v} · {L('máximo', 'maximum')}"); ax[1].set_aspect(ax[0].get_aspect())
                parts.append(f"<h3>{v}</h3><img src='{_png(fig)}' style='max-width:1000px'>")
            except Exception as ex:   # noqa: BLE001
                parts.append(f"<p class='warn'>{v}: {html.escape(str(ex))}</p>")
        if (wd / "station.in").exists() and (wd / "outputs" / "staout_1").exists():
            try:
                df = read_stations(wd, "elev")
                fig, ax = plt.subplots(figsize=(12, 4)); df.plot(ax=ax); ax.set_ylabel("elevación (m)"); ax.grid(alpha=.3)
                parts.append(f"<h3>{L('Estaciones', 'Stations')}</h3><img src='{_png(fig)}' style='max-width:1000px'>")
            except Exception as ex:   # noqa: BLE001
                parts.append(f"<p class='warn'>staout: {html.escape(str(ex))}</p>")
        if "layer" in ds.dims and any(v in ds for v in ("temperature", "salinity")):
            try:
                from ..gui.app import vgrid_of
                vg = vgrid_of(cfg, wd)
                y = float(ds.y.mean()); p0 = (float(ds.x.min()) + 0.05, y); p1 = (float(ds.x.max()) - 0.05, y)
                fig, ax = plt.subplots(figsize=(12, 4))
                plot_section(ds, "temperature" if "temperature" in ds else "salinity", p0, p1, vg, time=-1, ax=ax)
                parts.append(f"<h3>{L('Sección vertical (oeste-este por el centro)', 'Vertical section (west-east through the centre)')}</h3><img src='{_png(fig)}' style='max-width:1000px'>")
            except Exception as ex:   # noqa: BLE001
                parts.append(f"<p class='warn'>{L('sección', 'section')}: {html.escape(str(ex))}</p>")
    style = """<link href="https://fonts.googleapis.com/css2?family=Space+Grotesk:wght@400;700&family=JetBrains+Mono&display=swap" rel="stylesheet"><style>body{font-family:'Space Grotesk',Helvetica,Arial,sans-serif;max-width:1100px;margin:30px auto;color:#2b2b2b;padding:0 16px}
h1{color:#2b2b2b;border-bottom:3px solid #2b2b2b;padding-bottom:8px}h1 span{color:#0e9aa7;font-weight:400}h2{color:#2b2b2b;border-left:4px solid #0e9aa7;padding-left:10px;margin-top:36px}td,pre,code{font-family:'JetBrains Mono',Menlo,monospace}table{border-collapse:collapse}td{border:1px solid #ddd;padding:4px 10px}
td.help{color:#666;font-size:0.9em}pre{background:#f6f8fa;padding:10px;border-radius:8px;overflow:auto;font-size:12px}.meta{color:#666}.warn{color:#b00}
img{display:block;margin:10px 0;border:1px solid #eee;border-radius:8px}@media print{details{display:none}}</style>"""
    out.write_text(f"<!doctype html><html lang='{lang}'><head><meta charset='utf-8'><title>{html.escape(str(cfg.get('name', wd.name)))} · SCHISMlab</title>{style}</head><body>"
                   + "\n".join(parts) + "</body></html>", encoding="utf-8")
    return out
